// Generates src/data/heroArt.generated.ts: the Hero Banner's rotating messages as figlet (Standard) art.
// Run with `npm run generate:hero-art` and commit the output.
import { writeFileSync } from 'node:fs'
import figlet from 'figlet'

const MESSAGES = ['Mike Deiters', 'Sr. Engineer', 'Full-Stack', 'Atlanta, GA']

// The two slashes of "//", drawn once and shared by every message (same art as the old section banner).
const SLASH_ROWS = ['     ____', '    / / /', '   / / /', '  / / /', ' /_/_/']
const SLASH_WIDTH = 9
const SLASH_SPLIT = 6 // first "/" is columns [0, 6), second is [6, 10) with the blank column after them
const NAME_OFFSET = SLASH_WIDTH + 1

// Ranges of M i k e _ D e i t e r s within the name art, as hand-authored for the original static data.
const NAME_GLYPH_COLUMNS = [
  [0, 9], [9, 11], [11, 15], [15, 20], [20, 21], [21, 28], [28, 33], [33, 35], [35, 38], [38, 43], [43, 47], [47, 52],
].map(([start, end]) => [start + NAME_OFFSET, end + NAME_OFFSET])

const render = (text) => {
  const rows = figlet.textSync(text, { font: 'Standard' }).split('\n')
  while (rows.length > 1 && rows[rows.length - 1].trim() === '') rows.pop()
  const width = Math.max(...rows.map((row) => row.length))
  return rows.map((row) => row.padEnd(width))
}

function buildMessage(body) {
  const art = render(body)
  const rows = art.map((row, i) => (SLASH_ROWS[i] ?? '').padEnd(SLASH_WIDTH) + ' ' + row)
  const width = Math.max(...rows.map((row) => row.length))

  // Letters are smushed together, so a column shared by two letters belongs to the earlier one: a glyph ends where
  // the art for the text up to and including it ends.
  const glyphColumns = [[0, SLASH_SPLIT], [SLASH_SPLIT, NAME_OFFSET]]
  let start = 0
  for (let i = 1; i <= body.length; i++) {
    const naturalEnd = i === body.length ? art[0].length : render(body.slice(0, i))[0].length
    const end = Math.max(naturalEnd, start + 1) // a fully smushed glyph (e.g. ".") still gets a column to be typed
    glyphColumns.push([start + NAME_OFFSET, end + NAME_OFFSET])
    start = end
  }
  // The name's ranges were drawn by hand before this script existed; keep them exactly (k, t and r end one column
  // earlier than the rule above gives).
  if (body === 'Mike Deiters') glyphColumns.splice(2, 12, ...NAME_GLYPH_COLUMNS)
  return { text: `// ${body}`, rows: rows.map((row) => row.padEnd(width)), glyphColumns }
}

const messages = MESSAGES.map(buildMessage)
const out = `// Generated by scripts/generate-hero-art.mjs (figlet, Standard font). Do not edit by hand.
export interface HeroMessage {
  text: string
  /** Equal-width rows of art. */
  rows: string[]
  /** Column range [start, end) of each glyph: "/", "/", then one per character. */
  glyphColumns: [number, number][]
}

export const HERO_MESSAGES: HeroMessage[] = ${JSON.stringify(messages, null, 2)}
`
writeFileSync(new URL('../src/data/heroArt.generated.ts', import.meta.url), out)
